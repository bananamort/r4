//! Tests for filesystem-backed module resolution and file-based comments.

use std::fs;
use std::path::PathBuf;

use r4::generator::{LuaGenerator, TokenBasedLuaGenerator};
use r4::modules::{FileSystemModuleProvider, ModuleProvider};
use r4::rules::formatting::append_text_comment_from_file;
use r4::rules::AppendLocation;
use r4::Parser;

fn scratch_directory(name: &str) -> PathBuf {
    let directory = std::env::temp_dir().join(format!(
        "r4-io-{name}-{}-{:?}",
        std::process::id(),
        std::thread::current().id()
    ));
    let _ = fs::remove_dir_all(&directory);
    fs::create_dir_all(&directory).expect("the scratch directory is created");
    directory
}

#[test]
fn filesystem_provider_reads_nested_modules() {
    let root = scratch_directory("provider");
    fs::create_dir_all(root.join("pkg")).expect("nested directory");
    fs::write(root.join("pkg/util.lua"), "return { value = 1 }").expect("module file");

    let provider = FileSystemModuleProvider::new(&root);
    assert_eq!(
        provider.load("pkg/util").expect("load").as_deref(),
        Some("return { value = 1 }")
    );
    assert_eq!(provider.load("pkg/missing").expect("load"), None);
    assert_eq!(
        provider.path_for("pkg/util"),
        Some(root.join("pkg").join("util.lua"))
    );

    let _ = fs::remove_dir_all(&root);
}

#[test]
fn filesystem_provider_resolves_folder_modules_and_extensions() {
    let root = scratch_directory("folders");
    fs::create_dir_all(root.join("pkg/mod")).expect("folder module directory");
    fs::write(root.join("pkg/mod/init.lua"), "return 'folder'").expect("init file");
    fs::write(root.join("pkg/typed.luau"), "return 'typed'").expect("luau file");

    let provider = FileSystemModuleProvider::new(&root);
    assert_eq!(
        provider.load("pkg/mod").expect("load").as_deref(),
        Some("return 'folder'")
    );
    assert_eq!(
        provider.load("pkg/typed").expect("load").as_deref(),
        Some("return 'typed'")
    );

    // The folder module candidate is listed after the flat files.
    let candidates = provider.candidate_paths("pkg/mod");
    assert_eq!(candidates.first(), Some(&root.join("pkg").join("mod.lua")));
    assert!(candidates.contains(&root.join("pkg").join("mod").join("init.lua")));

    let _ = fs::remove_dir_all(&root);
}

#[test]
fn filesystem_provider_rejects_escaping_keys() {
    let provider = FileSystemModuleProvider::new("/tmp/r4-root");
    assert_eq!(provider.path_for("../secret"), None);
    assert_eq!(provider.path_for("pkg/../../secret"), None);
    assert!(provider.candidate_paths("../secret").is_empty());
    assert!(!provider.candidate_paths("pkg/util").is_empty());
}

#[test]
fn append_text_comment_reads_a_file() {
    let root = scratch_directory("comment");
    let path = root.join("banner.txt");
    fs::write(&path, "generated by r4").expect("banner file");

    let code = "return 1\n";
    let mut block = Parser::default()
        .preserve_tokens()
        .parse(code)
        .expect("valid code");
    append_text_comment_from_file(&mut block, &path, AppendLocation::Start)
        .expect("the file is readable");

    let mut generator = TokenBasedLuaGenerator::new(code);
    generator.write_block(&block);
    let output = generator.into_string();
    assert!(output.contains("--generated by r4"), "{output}");

    let _ = fs::remove_dir_all(&root);
}

#[test]
fn filesystem_provider_reports_unreadable_modules() {
    let root = scratch_directory("unreadable");
    fs::create_dir_all(root.join("pkg")).expect("nested directory");
    // A module that exists but is not valid UTF-8 must be a read error, not a
    // missing module.
    fs::write(root.join("pkg/binary.lua"), [0xff, 0xfe, 0x00]).expect("binary file");

    let provider = FileSystemModuleProvider::new(&root);
    let error = provider
        .load("pkg/binary")
        .expect_err("a non-UTF-8 module must not be reported as missing");

    assert!(matches!(error, r4::modules::ModuleLoadError::Read { .. }));
    assert_eq!(error.code(), "module/read");
    assert!(error.to_string().contains("pkg/binary"));

    let _ = fs::remove_dir_all(&root);
}
